  // recettes livrées, insuffisant pour en composer d'autres — et c'est bien ce qu'on
  // demande maintenant, depuis une conversation, en visant les macros qui restent sur
  // la journée. Un catalogue étroit oblige à inventer des identifiants, et un
  // identifiant inventé est refusé au dépôt : la composition tombe à l'eau.
  //
  // Ce qui a guidé le choix : des produits de supermarché français, disponibles toute
  // l'année, et surtout des aliments qui permettent d'AJUSTER — beaucoup de protéines
