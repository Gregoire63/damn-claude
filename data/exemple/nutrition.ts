  // fibreux — psyllium, graines de lin, herbes séchées — affiche moins de calories
  // ici que sur son emballage : l'étiquette, elle, compte les fibres dans l'énergie.
  // Garder l'étiquette ferait diverger les kcal du jour de ses propres macros.
  //
  // Un micronutriment n'est renseigné que quand la valeur est sûre. Une case vide se
